package playground;

public class CharPlusNumber {
    public static void main(String[] args) {
        char a = 'a';
        System.out.println(a+2);
        System.out.println((char)(a+2));

        System.out.println(a+3);
        System.out.println(a+4);
        System.out.println(a+10);
    }
}


